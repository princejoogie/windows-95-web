export function fileIcon(node: FsNode, small = false): ReturnType<typeof nodeIcon> {
  return node.kind === 'folder'
    ? { icon: small ? smallFolder : folder }
    : node.kind === 'drive'
      ? { icon: small ? icons.small.drive : icons.drive }
      : nodeIcon(node)
}
