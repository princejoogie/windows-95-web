import { pixelArt } from '../../icons/pixel'

function icon(rows: readonly string[]): string {
  return pixelArt(
    rows.flatMap((row) => {
      const scaled = row
        .padEnd(16, '.')
        .split('')
        .map((pixel) => pixel + pixel)
        .join('')
      return [scaled, scaled]
    }),
  )
}

