function contains(polygon: readonly Point[], x: number, y: number): boolean {
  let inside = false
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const a = polygon[i],
      b = polygon[j]
    if (a && b && a[1] > y !== b[1] > y && x < ((b[0] - a[0]) * (y - a[1])) / (b[1] - a[1]) + a[0])
      inside = !inside
  }
  return inside
}

const width = 180,
  height = 80
const mask = Array.from({ length: height }, (_, y) =>
  Array.from({ length: width }, (_, x) =>
    land.some((polygon) => contains(polygon, x * 2 - 180, 84 - y * 1.75)),
  ),
)

export function WorldMap({ offset }: { offset?: number }) {
  const src = useMemo(
    () =>
      pixelArt(
        mask.map((row, y) =>
          row
            .map((solid, x) => {
              const zone = offset !== undefined && Math.abs(x * 2 - 180 - offset / 4) < 7.5
              const border =
                solid &&
                [
                  [-1, 0],
                  [1, 0],
                  [0, -1],
                  [0, 1],
                ].some(([dx = 0, dy = 0]) => !mask[y + dy]?.[x + dx])
              return border ? 'g' : zone ? (solid ? 'w' : 'B') : solid ? 's' : 'C'
            })
            .join(''),
        ),
      ),
    [offset],
  )
  return (
    <img
      src={src}
      width={360}
      height={160}
      alt={offset === undefined ? 'World map' : 'Time zone map with the selected zone highlighted'}
      className="pixelated block w-full border border-shadow"
    />
  )
}
